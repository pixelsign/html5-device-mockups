// Compile modern model records into the two consumers; no runtime dependencies.
import {readFileSync, readdirSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
const root = new URL('../', import.meta.url);

export function readFamilies(dir) {
  const files = readdirSync(dir).filter(f=>f.endsWith('.json')).sort();
  if (!files.length) throw Error('No catalog families');
  const records = [], ids = new Set();
  for (const file of files) {
    for (const d of JSON.parse(readFileSync(join(dir,file)))) {
      if (ids.has(d.id)) throw Error(`Duplicate ${d.id} in ${file}`);
      ids.add(d.id); records.push(d);
    }
  }
  return records;
}

export function compile(records, prefix='modern') {
  const seen = new Set(), rows = [], picker = [], screenBeds = [];
  for (const d of records) {
    if (seen.has(d.id)) throw Error(`Duplicate id: ${d.id}`);
    seen.add(d.id);
    const colors = d.colors ?? Object.keys(d.finishes ?? {});
    const type = d.type ?? 'phone', fixed = type === 'laptop' || type === 'tv';
    if (!['phone','tablet','laptop','tv'].includes(type)) throw Error(`Invalid type: ${type}`);
    if (!/^[A-Za-z][\w-]*$/.test(d.id) || !d.label || !d.brand || !d.group || !d.provenance || !colors.length || new Set(colors).size !== colors.length || colors.some(c => !/^[a-z][\w-]*$/i.test(c))) throw Error(`Invalid model: ${d.id}`);
    const {width:w, height:h, screen:{x,y,width:sw,height:sh}} = d;
    if (![w,h,x,y,sw,sh].every(Number.isFinite) || x<0 || y<0 || sw<=0 || sh<=0 || x+sw>w || y+sh>h) throw Error(`Invalid screen: ${d.id}`);
    const t=y, r=w-x-sw, b=h-y-sh, l=x;
    const layouts = fixed ? [['landscape',[w,h,t,r,b,l]]] : [['portrait',[w,h,t,r,b,l]],['landscape',[h,w,r,b,l,t]]];
    // The masked content and SVG shell are rasterized separately. An opaque
    // glass bed underneath prevents the host colour showing at their shared edge.
    for (const [o,[fw,fh,top,right,bottom,left]] of layouts) {
      const radius=d.geometry?.screenRadius ?? 0;
      const radii=n=>d.geometry?.screenCorners==='top' ? `${n} ${n} 0 0` : n;
      const pct=(a,b)=>`${Number((100*a/b).toFixed(6))}%`;
      screenBeds.push(`  &[data-device="${d.id}"][data-orientation="${o}"]::before { inset: ${pct(top,fh)} ${pct(right,fw)} ${pct(bottom,fh)} ${pct(left,fw)}; border-radius: ${radii(pct(radius,fw-left-right))} / ${radii(pct(radius,fh-top-bottom))}; }`);
    }
    for (const c of colors) {
      for (const [orientation, geometry] of layouts) {
        rows.push(`    (${d.id}, ${orientation}, '${c}', true, ${geometry.join(', ')}, 0, 0, 0, 0)`);
      }
    }
    // Depth of an off-centre camera as a percentage of portrait screen height.
    // Content rotates independently of the frame: portrait top becomes landscape left.
    const cam = d.geometry?.camera;
    const statusClearance = type === 'phone' && cam?.centerX != null && cam.width > 0
      ? 100*(cam.top+cam.height)/sh : null;
    picker.push({...(statusClearance && {statusClearance}),id:d.id,label:d.label,group:d.group,brand:d.brand,type,...(d.previewOS && {previewOS:d.previewOS}),orientations:layouts.map(([o])=>o),colors,finishes:d.finishes || {},ext:'svg',synthLandscape:!fixed});
  }
  return {picker,sass:`// Generated by scripts/catalog.mjs. Edit catalog/families/*.json.\n${'$'}${prefix}Devices: (${[...seen].join(', ')}${seen.size===1?',':''});\n${'$'}${prefix}Rows: (\n${rows.join(',\n')}\n);\n@mixin ${prefix}-screen-beds {\n${screenBeds.join('\n')}\n}\n`};
}
if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const records = readFamilies(fileURLToPath(new URL('catalog/families/',root)));
  const large = readFamilies(fileURLToPath(new URL('catalog/large/',root)));
  if (large.some(d=>records.some(r=>r.id===d.id))) throw Error('Device ID overlaps phone catalog');
  const extra = compile(large,'large');
  const tvRecords = readFamilies(fileURLToPath(new URL('catalog/tvs/',root)));
  const tv = compile(tvRecords,'tv');
  const ids = [...records,...large,...tvRecords].map(d=>d.id.toLowerCase());
  if(new Set(ids).size!==ids.length) throw Error('Overlapping catalog IDs');
  writeFileSync(new URL('src/scss/_tvs.scss',root),tv.sass);
  const laptops = large.filter(d=>d.type==='laptop').map(d=>d.id);
  writeFileSync(new URL('src/scss/_large.scss',root),extra.sass+`$laptops: (${laptops.join(', ')},);\n`);
  const {sass,picker} = compile(records);
  writeFileSync(new URL('catalog/modern.json',root), JSON.stringify(records,null,2)+'\n');
  writeFileSync(new URL('src/scss/_modern.scss',root),sass);
  const dateDir = fileURLToPath(new URL('catalog/release-dates/',root));
  const releaseDates = Object.assign({}, ...readdirSync(dateDir).filter(f=>f.endsWith('.json')).sort().map(f=>JSON.parse(readFileSync(join(dateDir,f),'utf8'))));
  const releaseYears=JSON.parse(readFileSync(new URL('catalog/release-years.json',root),'utf8'));
  writeFileSync(new URL('dist/modern-picker.js',root),`// Generated demo metadata; not needed in embeds.\nconst RELEASE_DATES = ${JSON.stringify(releaseDates)};\nconst RELEASE_YEARS = ${JSON.stringify(releaseYears)};\nconst MODERN_PHONES = ${JSON.stringify(picker,null,2)};\nconst LARGE_DEVICES = ${JSON.stringify([...extra.picker,...tv.picker],null,2)};\n`);
}
